import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const sharp = createRequire(require.resolve('next/package.json'))('sharp');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256"><rect width="256" height="256" rx="58" fill="#27272a"/><g fill="none" stroke="#fafafa" stroke-width="11" stroke-linecap="round" stroke-linejoin="round"><path d="m65 100 63-34 63 34-63 34z"/><path d="m65 128 63 34 63-34M65 156l63 34 63-34"/></g></svg>`;
const png = await sharp(Buffer.from(svg)).png().toBuffer();
await writeFile(new URL('../public/icon.png', import.meta.url), png);
const header = Buffer.alloc(22);
header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4);
header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12);
header.writeUInt32LE(png.length, 14); header.writeUInt32LE(22, 18);
await writeFile(new URL('../build/icon.ico', import.meta.url), Buffer.concat([header, png]));
